# 🚀 Test: Bulk Create Customers
# ---------------------------
@pytest.mark.tcid("TCID-001")
@pytest.mark.bulk
@pytest.mark.contract
@pytest.mark.regression  # Bulk creation is heavier than smoke/sanity coverage.
@pytest.mark.parametrize("qty", [1, 3, 5])
def test_bulk_create_customers(
    qty,
    customer_helper,
    customers_dao,
    create_valid_customer,
):
    """
    Verify that multiple valid customers can be created and subsequently
    retrieved consistently through both the API and database.

    This test focuses on the bulk-creation workflow and intentionally does
    not provide scenario-specific customer fields such as billing or
    shipping addresses.

    Generic valid customer data is generated by the test-data layer:

        Test
          ↓
        create_valid_customer fixture
          ↓
        CustomerBuilder
          ↓
        CustomerFactory
          ↓
        CustomerProvisioner
          ↓
        CustomerHelper / CustomersApi
          ↓
        WooCommerce

    The CustomerFactory generates the generic valid customer data required
    for creation, including identity and address data.

    Address-specific scenarios are tested separately by TCID-004. Keeping
    those scenarios out of this bulk test ensures that each test has a
    focused responsibility.

    The create_valid_customer fixture is responsible for:
        - building valid customer creation data
        - provisioning the customer through the API
        - validating the creation response
        - registering the created customer for cleanup
        - returning the created customer data

    The bulk utility is responsible for:
        - calling create_fn() exactly ``qty`` times
        - collecting the identifiers of created customers
        - invoking validate_fn() for each created customer
        - reporting validation failures

    Test flow:
        1. Create ``qty`` valid customers through the test-data fixture.
        2. Collect each customer's email as its validation identifier.
        3. Retrieve each customer through the API.
        4. Retrieve each customer from the database.
        5. Verify that API and database data match.
        6. Allow the ownership/cleanup mechanism to remove all customers
           created by this test.

    Contract coverage:
        The test is marked as CONTRACT because create_valid_customer performs
        response validation using the customer response validation layer.
    """

    # ------------------------------------------------------------------
    # Step 1 — Define how one valid customer is created
    # ------------------------------------------------------------------
    def create_fn():
        """
        Create one valid customer through the standard test-data pipeline.

        No scenario-specific fields are supplied here. The CustomerFactory
        generates the complete valid customer payload.
        """
        customer = create_valid_customer()

        email = customer["email"]
        customer_id = customer["id"]

        logger.info(
            "📦 Created customer for bulk test: ID=%r, email=%r",
            customer_id,
            email,
        )

        # The bulk utility uses the email as the validation identifier.
        # Metadata is retained for logging/debugging consistency.
        return email, {
            "id": customer_id,
            "resource_type": "customers",
        }

    # ------------------------------------------------------------------
    # Step 2 — Define how one created customer is validated
    # ------------------------------------------------------------------
    def validate_fn(email):
        """
        Verify that the created customer exists and matches the database.

        Validation is intentionally performed after all requested customers
        have been created by the bulk utility.
        """

        # Retrieve customer through the API.
        api_customers = customer_helper.list_customers_paginated(
            email=email,
        )

        # Retrieve the same customer from the database.
        db_customer = customers_dao.get_customer_by_email(
            email=email,
        )

        # Verify API and database consistency.
        assert_customer_exists_and_matches_api(
            api_customers,
            email,
            db_customer,
        )

    # ------------------------------------------------------------------
    # Step 3 — Run the bulk create + validate workflow
    # ------------------------------------------------------------------
    bulk_create_and_validate_resources(
        create_fn=create_fn,
        validate_fn=validate_fn,
        qty=qty,
        label="customers",
    )


