@pytest.mark.tcid("TCID-006")
@pytest.mark.negative
@pytest.mark.contract
@pytest.mark.regression
def test_create_customer_fail_for_existing_email(
    create_valid_customer,
    customer_api_raw,
    customer_helper,
    customers_dao,
):
    """
    Verify that customer creation rejects an email address that already exists.

    This test intentionally combines two different test-data flows:

    1. Valid test-data setup:
       create_valid_customer()
           ↓
       CustomerBuilder
           ↓
       CustomerFactory
           ↓
       CustomerProvisioner
           ↓
       CustomerHelper / CustomersApi
           ↓
       WooCommerce

       The fixture creates the original customer and registers it for cleanup.

    2. Negative operation under test:
       Test
         ↓
       Raw API Client
         ↓
       POST /customers with the existing email
         ↓
       WooCommerce
         ↓
       HTTP 400

    The duplicate-email payload is intentionally constructed inside the test
    because it represents the invalid scenario being tested. It must not go
    through the valid-data Factory/Builder pipeline.

    Test flow:
        1. Create a valid customer through the test-data fixture.
        2. Extract the generated email from the created customer.
        3. Attempt to create another customer using the same email.
        4. Verify that WooCommerce returns HTTP 400.
        5. Validate the duplicate-email error response.
        6. Verify that the original customer still exists in the API.
        7. Verify that the original customer still matches the database record.
        8. Validate the error response against the error contract schema.

    Cleanup:
        The original customer is owned by this test and is automatically
        registered for cleanup by create_valid_customer().
    """

    # ------------------------------------------------------------------
    # Step 1 — Arrange: create a valid customer
    # ------------------------------------------------------------------
    logger.info(
        "🛠 Creating a valid customer to establish the duplicate-email scenario."
    )

    existing_customer = create_valid_customer()

    email = existing_customer["email"]
    customer_id = existing_customer["id"]

    logger.info(
        "📧 Existing customer created: ID=%r, email=%r",
        customer_id,
        email,
    )

    # ------------------------------------------------------------------
    # Step 2 — Arrange: build the intentionally invalid duplicate payload
    # ------------------------------------------------------------------
    # The email is valid in isolation but invalid for this operation because
    # it already belongs to an existing WooCommerce customer.
    payload = {
        "email": email,
        "password": "Password1",
    }

    logger.info(
        "⚠️ Attempting to create a duplicate customer using existing email: %r",
        email,
    )

    # ------------------------------------------------------------------
    # Step 3 — Act: attempt duplicate customer creation
    # ------------------------------------------------------------------
    http_response = customer_api_raw.post(
        endpoint="customers",
        payload=payload,
    )

    response = http_response.json

    # ------------------------------------------------------------------
    # Step 4 — Assert: transport-level validation
    # ------------------------------------------------------------------
    assert http_response.status_code == 400, (
        f"Expected 400 for duplicate customer email, "
        f"got {http_response.status_code}. "
        f"Response: {http_response.text[:300]}"
    )

    # ------------------------------------------------------------------
    # Step 5 — Assert: business-level validation
    # ------------------------------------------------------------------
    assert_customer_creation_failed(response)

    # ------------------------------------------------------------------
    # Step 6 — Assert: original customer still exists through the API
    # ------------------------------------------------------------------
    api_customers = customer_helper.list_customers_paginated(email=email)

    # ------------------------------------------------------------------
    # Step 7 — Assert: original customer still exists in the database
    #        and API/DB data remains consistent
    # ------------------------------------------------------------------
    db_customer = customers_dao.get_customer_by_email(email=email)

    assert_customer_exists_and_matches_api(
        api_customers,
        email,
        db_customer,
    )

    # ------------------------------------------------------------------
    # Step 8 — Assert: error response follows the API error contract
    # ------------------------------------------------------------------
    validate(
        instance=response,
        schema=error_schema,
    )

    logger.info(
        "✅ Duplicate customer creation correctly rejected: " "%s → %s: %s",
        payload,
        response["code"],
        response["message"],
    )
